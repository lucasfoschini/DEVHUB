// Generates dist/tokens.css from tokens.ts. Run: node src/build.ts
import { mkdirSync, writeFileSync } from 'node:fs'
import {
  breakpoints,
  elevation,
  font,
  glass,
  glassAlpha,
  glassTintStrength,
  motion,
  radius,
  space,
  themes,
  typeScale,
  zIndex,
  type Appearance,
  type ThemeColors,
} from './tokens.ts'

const kebab = (s: string) => s.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase())
const block = (selector: string, decls: string[]) =>
  `${selector} {\n${decls.map((d) => `  ${d};`).join('\n')}\n}`

const highlight = { dark: 'rgb(255 255 255 / 0.06)', light: 'rgb(255 255 255 / 0.7)' }

function themeDecls(name: keyof typeof themes): string[] {
  const t: ThemeColors = themes[name]
  return [
    `color-scheme: ${name}`,
    ...Object.entries(t).map(([k, v]) => `--dh-color-${kebab(k)}: ${v}`),
    `--dh-glass-highlight: ${highlight[name]}`,
  ]
}

function alphaDecls(a: Appearance): string[] {
  const decls = Object.entries(glassAlpha[a]).map(([k, v]) => `--dh-glass-alpha-${k}: ${v}%`)
  if (a === 'opaque') {
    decls.push(
      '--dh-glass-filter: none',
      '--dh-glass-filter-elevated: none',
      '--dh-glass-border: var(--dh-color-border-subtle)',
    )
  }
  return decls
}

const staticDecls = [
  ...space.map((v, i) => `--dh-space-${i}: ${v}px`),
  ...Object.entries(radius).map(([k, v]) => `--dh-radius-${k}: ${v}px`),
  `--dh-font-sans: ${font.sans}`,
  `--dh-font-mono: ${font.mono}`,
  ...Object.entries(typeScale).flatMap(([k, [size, line, weight, tracking]]) => [
    `--dh-text-${k}-size: ${size}px`,
    `--dh-text-${k}-line: ${line}px`,
    `--dh-text-${k}-weight: ${weight}`,
    `--dh-text-${k}-tracking: ${tracking}em`,
  ]),
  ...Object.entries(motion.duration).map(([k, v]) => `--dh-duration-${k}: ${v}ms`),
  ...Object.entries(motion.easing).map(([k, v]) => `--dh-ease-${k}: ${v}`),
  ...Object.entries(elevation).map(([k, v]) => `--dh-elevation-${k}: ${v}`),
  ...Object.entries(zIndex).map(([k, v]) => `--dh-z-${k}: ${v}`),
  ...Object.entries(breakpoints).map(([k, v]) => `--dh-breakpoint-${k}: ${v}px`),
]

// Derived values must live on the same element as the theme/material attributes (<html>).
const derivedDecls = [
  '--dh-color-fill-hover: color-mix(in srgb, var(--dh-color-text-primary) 6%, transparent)',
  '--dh-color-fill-selected: color-mix(in srgb, var(--dh-color-text-primary) 10%, transparent)',
  `--dh-glass-filter: blur(${glass.blur}px) saturate(${glass.saturate}%)`,
  `--dh-glass-filter-elevated: blur(${glass.elevatedBlur}px) saturate(${glass.saturate}%)`,
  '--dh-glass-border: color-mix(in srgb, var(--dh-color-text-primary) 10%, transparent)',
  `--dh-glass-tint-base: color-mix(in srgb, var(--dh-color-brand) ${glassTintStrength}%, var(--dh-color-glass-base))`,
  '--dh-material-regular-bg: color-mix(in srgb, var(--dh-color-glass-base) var(--dh-glass-alpha-regular), transparent)',
  '--dh-material-clear-bg: color-mix(in srgb, var(--dh-color-glass-base) var(--dh-glass-alpha-clear), transparent)',
  '--dh-material-tinted-bg: color-mix(in srgb, var(--dh-glass-tint-base) var(--dh-glass-alpha-tinted), transparent)',
  '--dh-material-elevated-bg: color-mix(in srgb, var(--dh-color-glass-base) var(--dh-glass-alpha-elevated), transparent)',
]

const glassClass = (name: string, filter: string, shadow = '') =>
  block(`.dh-material-${name}`, [
    `background: var(--dh-material-${name}-bg)`,
    `-webkit-backdrop-filter: var(${filter})`,
    `backdrop-filter: var(${filter})`,
    'border: 1px solid var(--dh-glass-border)',
    `box-shadow: inset 0 1px 0 var(--dh-glass-highlight)${shadow}`,
  ])

const css = [
  '/* Generated by @devhub/design-tokens (src/build.ts). Do not edit. */',
  block(':root', [
    ...themeDecls('dark'),
    ...staticDecls,
    ...alphaDecls('balanced'),
    ...derivedDecls,
  ]),
  block(":root[data-theme='light']", themeDecls('light')),
  `@media (prefers-color-scheme: light) {\n${block(':root:not([data-theme])', themeDecls('light'))}\n}`,
  ...(['clear', 'tinted', 'opaque'] as const).map((a) =>
    block(`:root[data-material='${a}']`, alphaDecls(a)),
  ),
  // Explicit in-app choice wins; without one, follow the OS.
  `@media (prefers-reduced-transparency: reduce) {\n${block(':root:not([data-material])', alphaDecls('opaque'))}\n}`,
  `@media (prefers-contrast: more) {\n${block(':root:not([data-material])', alphaDecls('opaque'))}\n${block(':root, :root[data-theme]', ['--dh-color-border-subtle: var(--dh-color-border-control)'])}\n}`,
  `@media (prefers-reduced-motion: reduce) {\n${block(
    ':root',
    Object.keys(motion.duration).map((k) => `--dh-duration-${k}: 1ms`),
  )}\n}`,
  block('.dh-material-solid', ['background: var(--dh-color-surface)']),
  block('.dh-material-subtle', ['background: var(--dh-color-fill-hover)']),
  glassClass('regular', '--dh-glass-filter'),
  glassClass('clear', '--dh-glass-filter'),
  glassClass('tinted', '--dh-glass-filter'),
  glassClass('elevated', '--dh-glass-filter-elevated', ', var(--dh-elevation-overlay)'),
  block('.dh-material-opaque', [
    'background: var(--dh-color-raised)',
    'border: 1px solid var(--dh-color-border-subtle)',
  ]),
].join('\n\n')

mkdirSync(new URL('../dist/', import.meta.url), { recursive: true })
writeFileSync(new URL('../dist/tokens.css', import.meta.url), css + '\n')
console.log('design-tokens: wrote dist/tokens.css')
